BOOL SBUIHasText(NSString *key) { return key && SBInterfaceTextCatalog()[key]!=nil; }
NSString *SBUIText(NSString *key) {
    NSString *text=key ? SBInterfaceTextCatalog()[key] : nil;
    if(text) return text;
#if DEBUG
    NSLog(@"SB_UI_TEXT missing authored interface key");
#endif
    // Fail neutrally: never expose a key, backend caption, or user value.
    return @"—";
}
// Catalog keys containers.count and containers.appCount are represented by
// these typed accessors because their format arguments must stay checked.
NSString *SBUIContainerCount(NSUInteger shown, NSUInteger total) {
    return [NSString stringWithFormat:@"%lu / %lu",(unsigned long)shown,(unsigned long)total];
}
NSString *SBUIAppCount(NSUInteger count) {
    return [NSString stringWithFormat:@"Apps: %lu",(unsigned long)count];
}
