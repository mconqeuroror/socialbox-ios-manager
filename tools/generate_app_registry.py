#!/usr/bin/env python3
"""Generate native descriptors from the cloud/native canonical registry."""
import argparse
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / "cloud/src/config/app-registry.json"
OUTPUT = ROOT / "shared/RBXAppRegistryData.h"
FIELDS = {
    "appType", "displayName", "sourceBundleIdentifier", "sourceBundleName",
    "cloneBundlePrefix", "keychainGroupPrefix", "teamIdentifier", "configNamespace",
    "sourceCachePath", "sourceDirectoryName", "sourceInboxPath", "cloneExportPath",
    "cloneMarkerName", "runnable", "iconName", "sourceImportRequestKey",
    "mdmExportDirectory", "mdmProfileFilename", "mdmMappingFilename", "originalDenyProfileId", "keychainInfoKeys",
    "keychainSourceGroups", "keychainGroupSuffixes",
}


def registry():
    rows = json.loads(SOURCE.read_text())
    if not isinstance(rows, list) or not rows:
        raise ValueError("Registry must be a nonempty array")
    for row in rows:
        if not isinstance(row, dict) or set(row) != FIELDS:
            raise ValueError("Descriptor fields do not match the registry schema")
        if type(row["runnable"]) is not bool:
            raise ValueError("runnable must be a JSON boolean")
        if any(not isinstance(row[key], str) or not row[key] or
               any(ord(char) < 32 for char in row[key]) for key in FIELDS - {"runnable", "keychainInfoKeys", "keychainSourceGroups", "keychainGroupSuffixes"}):
            raise ValueError("Descriptor strings must be nonempty and printable")
        keys = row["keychainInfoKeys"]
        if (not isinstance(keys, list) or any(not isinstance(key, str) or
                not re.fullmatch(r"[A-Za-z][A-Za-z0-9]+", key) for key in keys) or
                len(set(keys)) != len(keys)):
            raise ValueError("keychainInfoKeys must be unique literal Info.plist keys")
        groups, suffixes = row["keychainSourceGroups"], row["keychainGroupSuffixes"]
        if (not isinstance(groups, list) or any(not isinstance(group, str) or
                not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9.-]+", group) for group in groups) or
                len(set(groups)) != len(groups)):
            raise ValueError("keychainSourceGroups must be unique exact audited names")
        if (not isinstance(suffixes, list) or not suffixes or suffixes[0] != "" or
                any(not isinstance(suffix, str) or not re.fullmatch(r"(?:\.[a-z][a-z0-9]*)?", suffix) for suffix in suffixes) or
                len(set(suffixes)) != len(suffixes) or
                (len(groups) != len(suffixes) if groups else suffixes != [""])):
            raise ValueError("Keychain mapping must be one-to-one with primary group first")
        if not re.fullmatch(r"[a-z][a-z0-9_-]*", row["appType"]):
            raise ValueError("Invalid app type")
        if not re.fullmatch(r"[A-Za-z0-9.-]+", row["cloneBundlePrefix"]):
            raise ValueError("Invalid clone bundle prefix")
        if row["keychainGroupPrefix"] != row["teamIdentifier"] + ".":
            raise ValueError("Keychain group must use its own team identifier")
        if pathlib.PurePosixPath(row["sourceCachePath"]).name != row["sourceBundleName"]:
            raise ValueError("Source cache must end in source bundle name")
    for key in ("appType", "sourceBundleIdentifier", "cloneBundlePrefix", "keychainGroupPrefix",
                "teamIdentifier", "configNamespace", "sourceCachePath", "sourceDirectoryName", "cloneExportPath"):
        if len({row[key] for row in rows}) != len(rows):
            raise ValueError(f"Duplicate app-scoped field: {key}")
    prefixes = [row["cloneBundlePrefix"] for row in rows]
    if any(a.startswith(b) for a in prefixes for b in prefixes if a != b):
        raise ValueError("Clone bundle families must not overlap")
    return rows


def render(rows):
    lines = ["// Generated by tools/generate_app_registry.py; edit cloud/src/config/app-registry.json.",
             "#pragma once", "#import <Foundation/Foundation.h>",
             "static inline NSArray<NSDictionary *> *RBXAppRegistryGeneratedDescriptors(void) {", "    return @["]
    for row in rows:
        lines.append("        @{")
        for key, value in row.items():
            objc = ("@YES" if value else "@NO") if type(value) is bool else "@" + json.dumps(value, ensure_ascii=True)
            if isinstance(value, list):
                objc = "@[" + ", ".join("@" + json.dumps(item) for item in value) + "]"
            lines.append(f"            @{json.dumps(key)}: {objc},")
        lines.append("        },")
    lines.extend(["    ];", "}", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated native data is stale")
    args = parser.parse_args()
    generated = render(registry())
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            parser.error("Native app registry is stale; run tools/generate_app_registry.py")
        print("App registry: schema and generated native data match")
    else:
        OUTPUT.write_text(generated)


if __name__ == "__main__":
    main()
